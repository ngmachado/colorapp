// Generate knowledge records for the CSS named colours from a saved copy of the W3C specification
// CSS Color Module Level 4 (§ 6.1 Named Colors). The table there is normative: each keyword resolves to one sRGB
// value, so these are published values, not approximations.
//
//   node scripts/import-css-named-colours.mjs <css-color-4.html> > content/knowledge/web/css-named-colours.yaml
//
// Review state `extracted`, rights `verified-reusable` (W3C document licence). The spec's own history notes are kept
// as tags: the 16 keywords it says came from the VGA palette via HTML, and the one it added in Level 4. Seven grey spellings share a gray keyword's value.

import { readFileSync } from 'node:fs';

const SOURCE = 'w3c-css-color-4';
const LOCATOR = '§ 6.1 Named Colors, named-color table';
const [specPath] = process.argv.slice(2);
if (!specPath) {
  console.error('usage: import-css-named-colours.mjs <css-color-4.html>');
  process.exit(2);
}

// The spec: "16 of CSS's named colors come from the VGA palette originally, and were then adopted into HTML".
const VGA = new Set(
  'aqua black blue fuchsia gray green lime maroon navy olive purple red silver teal white yellow'.split(
    ' ',
  ),
);
// Two-word spellings kept as search aliases.
const ALIASES = { rebeccapurple: ['rebecca purple'] };
const NOTES = {
  rebeccapurple:
    'Added in Level 4 in memory of Rebecca Meyer; the only named colour not inherited from HTML or X11.',
};

const html = readFileSync(specPath, 'utf8');
const start = html.lastIndexOf('id="named-colors"');
const t0 = html.indexOf('<table class="named-color-table">', start);
const t1 = html.indexOf('</table>', t0);
if (t0 < 0 || t1 < 0) throw new Error('named-color table not found');
const table = html.slice(t0, t1);

const rows = [];
for (const m of table.matchAll(
  /id="valdef-color-([a-z]+)">\1<\/dfn>\s*<td>(#[0-9a-f]{6})\s*<td>(\d+) (\d+) (\d+)/g,
)) {
  const [, name, hex, r, g, b] = m;
  const fromHex = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
  if (fromHex.join(' ') !== `${r} ${g} ${b}`)
    throw new Error(`hex and decimal disagree for ${name}`);
  rows.push({ name, hex, rgb: [Number(r), Number(g), Number(b)] });
}
if (rows.length !== 148) throw new Error(`expected 148 named colours, parsed ${rows.length}`);

// gray/grey pairs are two keywords for one value: one concept, the other spelling as a second name.
const byHex = new Map();
for (const row of rows) {
  const stem = row.name.replace('grey', 'gray');
  const key = `${row.hex} ${stem}`;
  if (!byHex.has(key)) byHex.set(key, { ...row, name: stem, spellings: [] });
  if (row.name !== stem) byHex.get(key).spellings.push(row.name);
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const coords = (rgb) =>
  rgb.map((v) => (v / 255).toFixed(5).replace(/\.?0+$/, '') || '0').join(', ');
const out = [
  '# yaml-language-server: $schema=../schema.json',
  '# CSS named colours, generated by scripts/import-css-named-colours.mjs from a saved copy of CSS Color Module Level 4',
  '# (§ 6.1 Named Colors). The values are normative sRGB keywords, so every representation is a published value. The',
  '# seven grey/gray pairs are one concept each with both spellings as names. Do not edit by hand; rerun the script.',
  '',
];
let names = 0;
for (const c of byHex.values()) {
  const id = `css-${c.name}`;
  const tags = ['tradition: web', 'standard: css-color-4'];
  if (VGA.has(c.name)) tags.push('origin: vga-html');
  out.push(
    '- type: concept',
    `  id: ${id}`,
    '  review_state: extracted',
    '  rights_status: verified-reusable',
    `  evidence: { source: ${SOURCE}, locator: ${q(LOCATOR)} }`,
    `  label: ${c.name}`,
    `  description: ${q(
      `CSS named colour keyword; resolves to the sRGB value ${c.hex} in every conforming implementation.` +
        (VGA.has(c.name)
          ? ' One of the 16 keywords the specification says came from the VGA palette and were adopted into HTML.'
          : '') +
        (NOTES[c.name] ? ` ${NOTES[c.name]}` : ''),
    )}`,
    `  tags: { ${tags.join(', ')} }`,
    '',
  );
  for (const spelling of [c.name, ...c.spellings]) {
    names++;
    out.push(
      '- type: name',
      `  id: ${id}-${spelling === c.name ? 'en' : spelling}`,
      '  review_state: extracted',
      '  rights_status: verified-reusable',
      `  evidence: { source: ${SOURCE}, locator: ${q(LOCATOR)} }`,
      `  concept: ${id}`,
      `  script: ${spelling}`,
      '  language: en',
      ...(spelling !== c.name
        ? [
            `  notes: ${q(`Second keyword for the same value; the specification lists ${c.name} and ${spelling} separately.`)}`,
          ]
        : [...c.spellings, ...(ALIASES[c.name] ?? [])].length
          ? [`  aliases: [${[...c.spellings, ...(ALIASES[c.name] ?? [])].join(', ')}]`]
          : []),
      '',
    );
  }
  out.push(
    '- type: representation',
    `  id: ${id}-srgb`,
    '  review_state: extracted',
    '  rights_status: verified-reusable',
    `  evidence: { source: ${SOURCE}, locator: ${q(`${LOCATOR}, ${c.name} ${c.hex}`)} }`,
    `  concept: ${id}`,
    '  space: srgb',
    `  coords: [${coords(c.rgb)}]`,
    '  white: D65',
    `  method: ${q(`Normative sRGB value ${c.hex} (${c.rgb.join(' ')}) from the specification, divided by 255.`)}`,
    '  approximation_status: published-value',
    '  confidence: { transcription: 1, display: 1 }',
    '',
  );
}
process.stdout.write(out.join('\n'));
console.error(JSON.stringify({ keywords: rows.length, concepts: byHex.size, names }));
