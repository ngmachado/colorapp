// Embeds assets/*.svg into src/svg.generated.ts so the package stays pure (no file reads at runtime).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(import.meta.dirname, '..');
const views = ['front', 'back'] as const;
const entries = views.map((v) => {
  const svg = readFileSync(join(dir, 'assets', `${v}.svg`), 'utf8').trim();
  return `  ${v}: ${JSON.stringify(svg)},`;
});
writeFileSync(
  join(dir, 'src', 'svg.generated.ts'),
  `// Generated by scripts/embed.ts from assets/*.svg. Do not edit; edit the SVG files and run \`pnpm asset\`.\nimport type { View } from './types';\n\nexport const SVG: Record<View, string> = {\n${entries.join('\n')}\n};\n`,
);
console.log('embedded', views.join(', '));
